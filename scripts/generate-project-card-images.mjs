import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import sharp from "sharp";
import { loadSiteModule } from "./load-site-data.mjs";

// Maintenance command, separate from prebuild. Keep the original demo artwork.
// The first five catalog cards use these existing hero images; project detail
// pages have their own screenshots in app/lib/project-images.ts.
const gardenSources = {
  aquaverde: "/project-previews/aquaverde.webp",
  terraforma: "/project-previews/terraforma.webp",
  gazonpro: "/gazonpro/images/hero.webp",
  ecohabitat: "/ecohabitat/images/garden.jpg",
  yardcraft: "/yardcraft/images/hero-1600.webp",
};
const previewSources = {
  "serviceflow-pro": "/project-previews/serviceflow-pro.webp",
  "vatra-market": "/project-previews/vatra-market.webp",
  "codru-escapes": "/project-previews/codru-escapes.webp",
  "clientaxis-crm": "/project-previews/clientaxis-crm.webp",
  iclinica: "/project-previews/iclinica.webp",
};
const widths = [480, 800];
const digest = (buffer) => createHash("sha256").update(buffer).digest("hex");

export async function generateProjectCardImages(root = process.cwd()) {
  const { publicProjects } = loadSiteModule("app/lib/project-catalog.ts", root);
  const projects = publicProjects.filter(
    (project) =>
      gardenSources[project.slug] ||
      previewSources[project.slug] ||
      (project.id >= 27 && project.id <= 66),
  );
  const outputDirectory = path.join(root, "public/project-card-previews");
  await mkdir(outputDirectory, { recursive: true });
  const manifest = {};
  const records = [];

  for (const project of projects) {
    assert.match(project.slug, /^[a-z0-9-]+$/, "Expected a safe catalog slug");
    const source = gardenSources[project.slug] ?? previewSources[project.slug] ?? `/project-previews/${project.slug}.png`;
    const sourceFile = path.join(root, "public", source.slice(1));
    const original = await readFile(sourceFile);
    const originalHash = digest(original);
    const metadata = await sharp(original, { failOn: "error" }).metadata();
    const sourceWidth = metadata.autoOrient?.width ?? metadata.width;
    const sourceHeight = metadata.autoOrient?.height ?? metadata.height;
    assert.ok(sourceWidth > 0 && sourceHeight > 0, `Missing source dimensions: ${source}`);
    const variants = [];

    for (const targetWidth of widths) {
      const relative = `/project-card-previews/${project.slug}-${targetWidth}.webp`;
      const output = await sharp(original, { failOn: "error" })
        .rotate()
        .resize({ width: targetWidth, withoutEnlargement: true })
        .webp({ quality: 86, effort: 6 })
        .toBuffer({ resolveWithObject: true });
      assert.equal(output.info.format, "webp");
      assert.equal(output.info.width, Math.min(targetWidth, sourceWidth));
      assert.ok(output.info.height <= sourceHeight, `Unexpected upscaling: ${relative}`);
      await writeFile(path.join(root, "public", relative.slice(1)), output.data);
      variants.push({ src: relative, width: output.info.width, height: output.info.height, bytes: output.info.size });
    }

    // A future source smaller than either target is still never upscaled. Its
    // actual pixel width supplies the descriptor; duplicate widths are omitted.
    const uniqueVariants = [...new Map(variants.map((variant) => [variant.width, variant])).values()];
    const fallback = variants.at(-1);
    manifest[project.slug] = {
      fallback: fallback.src,
      srcSet: uniqueVariants.map((variant) => `${variant.src} ${variant.width}w`).join(", "),
      width: fallback.width,
      height: fallback.height,
    };
    assert.equal(digest(await readFile(sourceFile)), originalHash, `Source image changed: ${source}`);
    records.push({ slug: project.slug, source, sourceWidth, sourceHeight, sourceBytes: original.length, sourceSha256: originalHash, variants });
  }

  const generated = "// Generated by scripts/generate-project-card-images.mjs. Originals are preserved.\n"
    + "export const projectCardImages: Record<string, { fallback: string; srcSet: string; width: number; height: number }> = "
    + JSON.stringify(manifest, null, 2) + ";\n";
  await writeFile(path.join(root, "app/lib/project-card-images.ts"), generated);
  const report = {
    quality: 86,
    withoutEnlargement: true,
    projects: records.length,
    variants: records.reduce((count, record) => count + record.variants.length, 0),
    sourceBytes: records.reduce((sum, record) => sum + record.sourceBytes, 0),
    fallbackBytes: records.reduce((sum, record) => sum + record.variants.at(-1).bytes, 0),
    smallBytes: records.reduce((sum, record) => sum + record.variants[0].bytes, 0),
    records,
  };
  await mkdir(path.join(root, "reports/seo"), { recursive: true });
  await writeFile(path.join(root, "reports/seo/project-card-images.json"), JSON.stringify(report, null, 2) + "\n");
  return report;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const { projects, variants, sourceBytes, fallbackBytes, smallBytes } = await generateProjectCardImages();
  console.log(JSON.stringify({ projects, variants, sourceBytes, fallbackBytes, smallBytes }));
}
